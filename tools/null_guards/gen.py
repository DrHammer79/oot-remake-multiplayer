#!/usr/bin/env python3
"""Make the ExeFS module's null guard entries from tools/null_guards/sites.py, and check the copies.

    gen.py                 write switch/proto/null_guards.inc
    gen.py --check         fail when null_guards.inc is not what this writes, or when Hookshot patch 0023's table
                           (nx2/coop_null_guards.py inside hookshot/patches/0023-*.patch) differs from sites.py

sites.py is the one table (its docstring says why): change it, run gen.py, and make patch 0023's table the same
(--check names what differs).
"""
from __future__ import annotations

import argparse
import glob
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sites  # noqa: E402

INC = os.path.join(ROOT, "switch", "proto", "null_guards.inc")
PATCH_GLOB = os.path.join(ROOT, "hookshot", "patches", "0023-*.patch")
LIFT_FILE = "nx2/coop_null_guards.py"
TABLES = ("BUILD_ID", "PLAYER_OF", "PLAYER_LOADS", "PLAYER_LOADS_LATER", "SLOT10_LOADS")


def inc_text() -> str:
    lines = [
        "// Generated by tools/null_guards/gen.py from tools/null_guards/sites.py: do not edit.",
        "// Null guards (hooks.h kNullGuard), each after the kCheck entries that must hold for it.",
        "// Game build " + sites.BUILD_ID[:16] + " (1.1.1).",
        "#pragma once",
        "",
    ]
    entries = []
    for off, word, checks in sites.guards():
        rt, rn, imm = sites.decode(word)
        for c_off, c_word in checks:
            entries.append(f"    {{hooks::kCheck, 0, 0x{c_word:08x}u, 0x{c_off:x}u, nullptr, nullptr}},")
        entries.append(f"    {{hooks::kNullGuard, 0, 0x{word:08x}u, 0x{off:x}u, nullptr, nullptr}},"
                       f"  /* x{rt} <- [x{rn}, #0x{imm:x}] */")
    n_guards = len(sites.guards())
    lines.append(f"constexpr uint32_t kNullGuardCount = {n_guards};")
    lines.append(f"constexpr uint32_t kNullGuardEntries = {len(entries)};")
    lines.append("#define COOP_NULL_GUARD_ENTRIES \\")
    lines += [e + " \\" for e in entries[:-1]]
    lines.append(entries[-1])
    return "\n".join(lines) + "\n"


def lift_table(patch_text: str) -> dict:
    """The tables of nx2/coop_null_guards.py as patch 0023 adds it (the file's + lines, run in a namespace of its own)."""
    out, inside = [], False
    for line in patch_text.splitlines():
        if line.startswith("diff --git "):
            inside = line.endswith(" b/" + LIFT_FILE)
            continue
        if inside and line.startswith("+") and not line.startswith("+++"):
            out.append(line[1:])
    if not out:
        raise SystemExit(f"{LIFT_FILE} is not in the patch")
    ns: dict = {}
    exec(compile("\n".join(out), LIFT_FILE, "exec"), ns)  # (our own file, from our own repo)
    return {k: ns.get(k) for k in TABLES}


def check() -> list[str]:
    problems = []
    try:
        with open(INC, encoding="utf-8", newline="") as f:
            if f.read() != inc_text():
                problems.append(f"{os.path.relpath(INC, ROOT)} is not what gen.py writes: run tools/null_guards/gen.py")
    except FileNotFoundError:
        problems.append(f"no {os.path.relpath(INC, ROOT)}: run tools/null_guards/gen.py")
    patches = glob.glob(PATCH_GLOB)
    if patches:
        with open(patches[0], encoding="utf-8") as f:
            lift = lift_table(f.read())
        for k in TABLES:
            if lift[k] != getattr(sites, k):
                problems.append(f"{os.path.basename(patches[0])}: {k} differs from tools/null_guards/sites.py")
    else:
        print("note: no hookshot/patches/0023-*.patch on this branch: the lift's table is not compared")
    return problems


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    if a.check:
        problems = check()
        for p in problems:
            print("error: " + p, file=sys.stderr)
        if not problems:
            print(f"null guards: {len(sites.guards())} guards, the copies match")
        return 1 if problems else 0
    with open(INC, "w", encoding="utf-8", newline="\n") as f:
        f.write(inc_text())
    print(f"wrote {os.path.relpath(INC, ROOT)} ({len(sites.guards())} guards)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
