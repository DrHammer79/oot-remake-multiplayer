"""The game's loads that read through a co-op puppet's missing components: the one table both guards come from.

A co-op puppet (CoopPuppet_*) has no Player component (main+0x82acc0 returns 0 for it). Game code that runs for an
item it wears loads through that null pointer; the emulator reads 0 there, a recomp's host and a real Switch fault.
The slot-10 (Physics) reads are answered by the puppet pack's own Physics (tools/puppet_pack, v1-puppet-components);
the slot-10 loads stay listed for packs built without it (--no-cloth).

Two guards are made from this table, with the same meaning (a load whose base register holds a null pointer gives its
register 0, what the emulator reads; every other load runs as shipped):
- Longshot/Hookshot (lifted C): hookshot/patches/0023-coop-null-guards.patch, nx2/coop_null_guards.py, through
  a64_lift.py's Lifter.unless (base below 1 MB). tools/null_guards/gen.py --check compares that patch's table with
  this one.
- ExeFS (in the game's process): switch/proto/null_guards.inc, generated by tools/null_guards/gen.py: hook entries of
  kind null guard (and the checks before each), applied by the module's _init (switch/proto/null_guard.h; base 0).

Game build e0f3ccfaf50065ae (Ocarina of Time 1.1.1). Found from the players' and lane logs and a scan of main for
every caller of main+0x82acc0 that loads through x0 with no check (v1-nullreads-a, reports/v1-nullreads-a.md).
"""

MAIN = 0x80020000
BUILD_ID = "e0f3ccfaf50065ae4ea01eb5aeb13b1a45da3348"
PLAYER_OF = 0x82acc0     # [[x0+0x270]+0x358]: the actor's Player component, 0 when it has none
NULL_BELOW = 0x100000    # (the lift) a base below the guest's first MB is a null pointer

# (main offset, its word): loads through x0 straight after `bl main+0x82acc0`
PLAYER_LOADS = (
    (0x82ac1c, 0xf9400c08), (0x84a070, 0x3940b008), (0x26cf2a4, 0xb94e5814), (0x2731e50, 0x39797c08),
    (0x2733184, 0x39796808), (0x2794cf8, 0x3940c808), (0x27d470c, 0xb95be008), (0x27e4f6c, 0xf9400c08),
    (0x27fa83c, 0xb94e4408), (0x27fca9c, 0x39792008), (0x27fed04, 0x3978e408), (0x27ff61c, 0x3978e408),
    (0x280c6ec, 0x3940b808), (0x2b3093c, 0x3940c008), (0x2b30b70, 0xb9472c08), (0x2b37314, 0xf9400c08),
    (0x2dceef8, 0xb947d808), (0x2eae030, 0xb947d808), (0x2f49fd0, 0xb947d808), (0x2f49fe4, 0x39408c08),
    (0x2f9f9c0, 0x39797008), (0x2fa0e44, 0x39796c08), (0x2fa0ee8, 0x39796c08), (0x30507a0, 0x3940b008),
    (0x3050874, 0x3940b008),
)
# (main offset, its word, the `bl main+0x82acc0` before it, the words between that leave x0 alone)
PLAYER_LOADS_LATER = (
    (0x27975f0, 0x395f0408, 0x27975d0, ((0x27975d4, 0x394422a8),    # ldrb w8, [x21, #0x108]
                                         (0x27975d8, 0x360000c8))),  # tbz w8, #0, main+0x27975f0
)
# (main offset, its word): slot 10 in f_804d84b0
SLOT10_LOADS = ((0x4b85e4, 0xf9402908), (0x4b85e8, 0xf9401108), (0x4b85ec, 0xf940e508))

# LDR (64/32), LDRH, LDRB with an unsigned immediate offset: (mask, value, bytes)
LOADS = ((0xffc00000, 0xf9400000, 8), (0xffc00000, 0xb9400000, 4), (0xffc00000, 0x79400000, 2),
         (0xffc00000, 0x39400000, 1))


def decode(word):
    """(dest register, base register, offset) of a load the guards know, else None"""
    for mask, value, size in LOADS:
        if word & mask == value:
            return word & 31, (word >> 5) & 31, ((word >> 10) & 0xfff) * size
    return None


def bl(pc, target):
    """The word of `bl target` at pc (main offsets)"""
    return 0x94000000 | (((target - pc) >> 2) & 0x3FFFFFF)


def guards():
    """Every guard, in main order: (main offset, its word, ((main offset, word) that must hold before it is applied))."""
    out = [(off, w, ((off - 4, bl(off - 4, PLAYER_OF)),)) for off, w in PLAYER_LOADS]
    out += [(off, w, ((call, bl(call, PLAYER_OF)),) + tuple(between)) for off, w, call, between in PLAYER_LOADS_LATER]
    out += [(off, w, ()) for off, w in SLOT10_LOADS]
    return sorted(out)
